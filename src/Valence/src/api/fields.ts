import snapshot from './model-fields.snapshot.json';

/** One validator rule of a field, as `GET /model/fields` describes it (BaseApi's `ModelRuleDto`). */
export interface ModelRule {
  /** required, notNull, maxLength, minLength, length, pattern, enum, notEqual, equal — or code: only BaseApi can run it. */
  kind: string;
  value: string | null;
  /** The rule's own message; null: FluentValidation's default. */
  message: string | null;
  /** Applies only under a condition (e.g. only when the field is given). */
  conditional: boolean;
}
export interface ModelField {
  field: string;
  column: string | null;
  type: string;
  nullable: boolean;
  storeType: string | null;
  rules: ModelRule[];
  values: { value: number; name: string }[] | null;
}
export interface ModelEntityFields { table: string; fields: ModelField[]; unique: { index: string; fields: string[]; filter: string | null }[] }
export interface ModelFields { etag: string; entities: ModelEntityFields[] }

/** Where the rules in use came from: BaseApi itself, or the bundled snapshot when this BaseApi has no endpoint for them. */
export interface RulesSource { from: 'baseapi' | 'snapshot'; fields: ModelFields; note: string }

/**
 * The bundled copy of `GET /model/fields`, generated by BaseApi's `ValenceFieldsSnapshotTests` (which fail when it
 * drifts): the rules Valence uses until BaseApi answers, or when BaseApi is older than the endpoint.
 */
export const SNAPSHOT: ModelFields = snapshot as ModelFields;

/**
 * Reads the rules from BaseApi (decision 5: the rules come from BaseApi). A BaseApi without the endpoint, or one that
 * cannot be reached, leaves the snapshot in use and says so; nothing throws.
 */
export async function readFields(fetchFn: typeof fetch = fetch): Promise<RulesSource> {
  const fallback = (why: string): RulesSource => ({ from: 'snapshot', fields: SNAPSHOT, note: `Rules: the bundled snapshot of GET /model/fields (${why}).` });
  try {
    const res = await fetchFn('/api/v1/model/fields', { headers: { Accept: 'application/json' } });
    if (!res.ok) return fallback(res.status === 404 ? 'this BaseApi has no GET /model/fields yet' : `GET /api/v1/model/fields: ${res.status}`);
    const body = (await res.json()) as { entities?: unknown };
    if (!Array.isArray(body.entities)) return fallback('GET /api/v1/model/fields: not a description');
    const etag = (res.headers.get('ETag') ?? '').replace(/^W\//, '').replace(/"/g, '');
    return { from: 'baseapi', fields: { etag, entities: body.entities as ModelEntityFields[] }, note: 'Rules: from BaseApi, GET /model/fields.' };
  } catch (e) {
    return fallback(`BaseApi could not be read: ${e instanceof Error ? e.message : String(e)}`);
  }
}
