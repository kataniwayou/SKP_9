def grafana11_axis_fix(panels):
    """Drop `decimals` from any timeseries that also sets `noValue`. Grafana 11.1 only.

    MEASURED ON A REAL grafana/grafana:11.1.0 AGAINST THIS BOARD. A timeseries carrying
    BOTH `decimals: 0` and a `noValue` string renders that string as its Y-AXIS TICK
    LABELS, once per tick it cannot format, wiping out the axis:

        11.1.0                                     12.3.9
          2                                          2
        o gate reporting -- this replica is not..
          1  ------------------------               1  ------------------------
        o gate reporting -- this replica is not..
          0                                          0

    The trigger is an auto-scaled axis landing on FRACTIONAL ticks -- data topping out
    at 1 with `min: 0` scales to 0..2 and ticks every 0.5, which `decimals: 0` cannot
    render, so 11.1 substitutes noValue where 12.x drops the tick. It is therefore
    DATA-DEPENDENT: `Queue depth by queue` and `Consumers attached by queue` escape
    today only because their ranges (0..100, 0..3) happen to tick on integers, and would
    break the moment a range shrank to 0..2.

    Three variants were rendered side by side at the real 8-wide grid size:
      A  decimals + noValue   -> axis destroyed
      B  no decimals          -> clean, noValue preserved
      C  no noValue           -> clean, message lost
    B is applied here. The noValue strings are load-bearing -- they are what separates
    "nothing is probing this queue" from "this queue is empty", a distinction several
    panel descriptions depend on -- so losing them to fix an axis is the wrong trade.
    The cost is fractional ticks on a small range, which is cosmetic.

    Expressed as a RULE rather than a list of four panel titles, so a panel that gains a
    noValue later cannot quietly reintroduce the defect.

    Stat panels are untouched: they have no axis, and `Dead-letter depth (all queues)`
    carries both properties while rendering correctly on 11.1.
    """
    fixed = []

    def walk(ps):
        for p in ps:
            if p.get("type") == "row":
                walk(p.get("panels", []))
                continue
            defaults = p.get("fieldConfig", {}).get("defaults", {})
            if (p.get("type") == "timeseries"
                    and defaults.get("noValue") is not None
                    and defaults.get("decimals") is not None):
                del defaults["decimals"]
                fixed.append(p["title"])

    walk(panels)
    return fixed


def relayout(panels):
    """Recompute every gridPos from the FINAL panel order.

    Layout assigns positions as panels are CREATED, which is fine while creation order
    and display order are the same thing. They stopped being the same when the boards
    were regrouped by subject: `pipeline_shared` builds six panels that now belong to
    three different rows, and splitting the helper three ways to preserve creation order
    would have coupled it to one board's layout.

    So position is decided last, from the list as assembled. Expanded rows carry their
    children as siblings and collapsed rows carry them nested; both are walked, because
    a collapsed row's children still need absolute y positions continuing below the
    header -- see row().
    """
    lay = Layout()

    def place(panel):
        pos = panel["gridPos"]
        panel["gridPos"] = lay.place(pos["w"], pos["h"])

    for panel in panels:
        if panel.get("type") == "row":
            lay.newline()
            panel["gridPos"] = lay.place(24, 1)
            for child in panel.get("panels", []):
                place(child)
            continue
        place(panel)

    return panels



def regroup(panels, plan):
    """Re-sort a built board into subject rows, by panel title.

    The rows used to split by TENSE at the top (Verdict / Since, the same instruments
    twice) and then lump fifteen panels under one question. This groups by subject
    instead -- what is flowing, what is waiting, whether the replica can work -- so a
    row header predicts its contents.

    Applied as a post-pass rather than by restructuring the helpers, for the reason
    relayout() exists: `pipeline_shared` builds six panels that now land in three
    different rows, and no helper should have to know one board's row plan.

    RAISES on any panel the plan does not name, and on any name matching no panel. A
    regroup that silently drops a panel is how a board loses one without anybody
    noticing, and this file has already shipped that failure twice.
    """
    lay = Layout()
    flat, collapsed = {}, {}
    for panel in panels:
        if panel.get("type") == "row":
            collapsed[panel["title"]] = panel
            continue
        flat[panel["title"]] = panel

    out, used = [], set()
    for row_title, titles in plan:
        if titles is None:                      # an existing row, carried over whole
            out.append(collapsed[row_title])
            continue
        out.append(row(lay, row_title))
        for title in titles:
            if title not in flat:
                raise SystemExit(f"regroup: no panel titled {title!r}")
            out.append(flat[title])
            used.add(title)

    orphans = sorted(set(flat) - used)
    if orphans:
        raise SystemExit(f"regroup: these panels are in no row: {orphans}")
    return out



