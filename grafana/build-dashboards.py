def build_processor():
    lay = Layout()
    # PROCESSOR ID AND REPLICA ONLY -- service_name and service_version are no longer
    # selectors, so they are no longer filters either.
    #
    # `processorId!=""` is what keeps the board to processors. A bare
    # `processorId=~"$processorId"` does NOT: with All resolving to `.*`, an empty label
    # matches, so every orchestrator and API series would satisfy it -- the same trap the
    # old `all_value=None` on service_name existed to avoid, one label along.
    f = ('processorId=~"$processorId",processorId!="",'
         'service_instance_id=~"$service_instance_id"')
    panels = []

    panels.append(row(lay, "1 - Verdict: is the processor broken?"))
    v = verdict_shared(lay, f, by_="service_instance_id")
    # v[:1] is the posture half (L2 gate) and v[1:] the fault counters. It was v[:2] /
    # v[2:] while `Consuming` led the list; that stat is gone with its instrument.
    panels += v[:1]
    panels += [
        stat(lay, "Identity ready",
             [f'min by (service_instance_id) '
              f'({live(f"pipeline_identity_ready_ratio{{{f}}}")})'],
             desc="0 means the pod is up and waiting for a processor row whose "
                  "SourceHash matches its image. Running / NotReady with 0 restarts is "
                  "the designed behaviour, not a crash loop -- this is the metric that "
                  "makes that legible.",
             thresholds=T_POSTURE, decimals=0),
    ]
    panels += v[1:]

    lay.newline()
    panels.append(row(lay, "2 - Since: what has already happened?"))
    panels += since_shared(lay, f, restarts=False, by_="service_instance_id")
    panels += [
        stat(lay, "Restarts",
             [f'max by (service_instance_id) (changes('
              f'pipeline_process_start_timestamp_seconds{{{f}}}[$__range]))'],
             desc="How many times any replica restarted, over the visible range. The gauge holds "
                  "the process start time and moves exactly once per process, so "
                  "changes() over a window is the restart count." + PARA +
                  "**It works because InstanceId resolves to POD_NAME**, which is stable "
                  "across container restarts within a pod -- a restart moves the value on "
                  "an EXISTING series rather than creating a new one, which is what "
                  "changes() needs to see it at all." + PARA +
                  "`max` rather than `sum` across replicas: this answers *did anything "
                  "restart*, and a sum would report a rollout of two replicas as two "
                  "restarts of one." + PARA +
                  "**It is now the ONLY restart signal on this board, and the two "
                  "`Process restarts` panels that used to sit beside it are gone.** They "
                  "read `resets()` on the JIT-compiled-methods counter, which cannot see "
                  "a restart on this deployment: a rollout replaces the pod, so the old "
                  "series ends and a new one is born under a new `service_instance_id` "
                  "rather than going backwards. Measured minutes after a deliberate "
                  "rollout that replaced both replicas, `sum(resets(...[30m]))` was 0 "
                  "against a live counter at ~16.9k. Two panels showing a confident zero "
                  "for an event that had just happened is worse than one panel showing "
                  "the truth." + PARA +
                  "**The window follows the visible range** rather than a fixed hour, so "
                  "this reads the same tense as everything else on the Since tier. Zoom "
                  "out and the count grows because you are asking about more time.",
             thresholds=T_WARN, decimals=0),
    ]

    panels.append(row(lay, "3 - Pipeline: what is broken?"))
    panels += pipeline_shared(lay, f, consumed_seed=DISPOSITIONS,
                              enumerate_names=True)
    panels += [
        timeseries(lay, "L2 gate and trips by replica",
                   [(f'{live(f"pipeline_gate_open_ratio{{{f}}}")}',
                     "gate {{service_instance_id}}"),
                    (f'increase(pipeline_gate_trips_total{{{f}}}[$__range])',
                     "trips {{service_instance_id}}")],
                   desc="The gate's posture per replica, and how many times it has "
                        "tripped over the visible range." + PARA +
                        "**The two are paired because the gauge alone cannot see a fault "
                        "that healed.** A trip that closed the gate and reopened it "
                        "leaves the gauge back at 1 with nothing to show, and the verdict "
                        "stat beside it green -- while the counter keeps the fact for the "
                        "whole range. A store that is flapping reads as a healthy store on every "
                        "posture signal on this board except this line." + PARA +
                        "**A trips series that is ABSENT means never tripped, not never "
                        "measured.** `pipeline.gate.trips` is a .NET counter, created on "
                        "first increment, so there is no series at all until the first "
                        "trip -- unlike `pipeline.loop.iterations`, which is seeded. "
                        "Checked against Prometheus at the time of writing: the name "
                        "exists in the series index from an earlier trip, and carries no "
                        "current samples. The gate line draws either way, so this panel "
                        "is not empty when the counter is." + PARA +
                        "Exported as `_total` with no `_ratio`, despite the instrument's "
                        "`unit: \"1\"`. That suffix is applied to the GAUGES -- "
                        "`pipeline_gate_open_ratio` on this very panel is one of them -- "
                        "and not to counters. Verified against Prometheus's series index, "
                        "because a wrong name here fails to no-data rather than to an "
                        "error." + PARA +
                        "**One axis, two magnitudes, on purpose.** The gate is 0 or 1 and "
                        "the trips count is small, so they read together; in health every "
                        "replica's gate sits at exactly 1 and the lines overlap into one, "
                        "which is why the instantaneous answer belongs to the `L2 gate` "
                        "verdict stat and the HISTORY belongs here." + PARA +
                        "**The window follows $__range rather than a fixed hour.** The fixed "
                        "hour was chosen so the number would not move when the reader "
                        "zoomed; the cost was a panel whose window disagreed with every "
                        "neighbour and with its own legend. Zoom out and the count grows "
                        "because you are asking about more time.",
                   minv=0, decimals=0,
                   no_value="no gate reporting -- this replica is not exporting at all"),
        statetimeline(lay, "Identity ready by replica",
                   [(f'{live(f"pipeline_identity_ready_ratio{{{f}}}")}',
                     "{{service_instance_id}}")],
                   desc="One row per replica that is still reporting. Red is a pod that "
                        "is up and waiting for a processor row matching its image -- the "
                        "designed behaviour, not a crash loop." + PARA +
                        "Unrestricted, this panel GAINS series during a rollout: the "
                        "departed replicas are held by the collector and Prometheus while "
                        "their replacements start exporting, so two live processors "
                        "rendered as four series all sitting at 1. A row that ends is a "
                        "replica that left." + PARA +
                        "Drawn as a state timeline for that reason among others: four "
                        "overlapping filled areas at the same value are one opaque block, "
                        "and which of the four had ended was not readable from it.",
                   mappings=M_READY),
        # TWO PANELS AND A STAT ARE GONE FROM THIS ROW, WITH THE INSTRUMENTS THEY READ.
        #
        # `Duplicate suppression rate` and `Duplicates suppressed` read
        # pipeline.duplicate.suppressed, and `Process duration p95 / p99 by outcome` read
        # pipeline.process.duration. Both are retired -- section 6 of the 2026-08-26
        # metrics-rewrite spec.
        #
        # The duplicate path is not unmeasured, it is folded in: that branch returns
        # normally and the delivery is ACKed, so it now counts as an acked delivery like
        # any other. The cost is that the acked count mixes real transform runs with
        # skipped duplicates, and the 'entry absent' condition -- which ProcessDispatchHandler
        # documents as possibly a silent LOSS rather than a safe duplicate -- has only its
        # log line left. Recorded here because no panel can now show it.
        #
        # Process duration is subsumed by `Consumer duration by disposition` below, which
        # measures more rather than less: the transform plus everything around it, on every
        # exit path including the ones that never reached a handler at all.
        *depth_panels(lay, 'queue=~"processor-$processorId"', "this processor's work queue",
                      enumerate_names=True, service_f="," + f),
        timeseries(lay, "Replica fan-out",
                   [(f'sum by (service_instance_id) (rate(pipeline_messages_consumed_total'
                     f'{{{f},disposition="acked"}}[$__rate_interval])) '
                     f'and on(service_instance_id) '
                     f'present_over_time(pipeline_identity_ready_ratio{{{f}}}[{LIVENESS}])',
                     "{{service_instance_id}}")],
                   desc="Replicas share one queue, so the broker round-robins. A "
                        "replica sitting near zero while the others work is consuming "
                        "nothing despite looking healthy." + PARA +
                        "**A line that ENDS is a replica that left; a line flat at zero "
                        "beside working peers is a replica that stopped working.** The "
                        "`and on(service_instance_id) present_over_time(...)` clause ends "
                        "the line a fixed ~40s after a replica's last export, whatever "
                        "the dashboard's time range." + PARA +
                        "Without it the end of the line moves with the range. A departed "
                        "replica's counter is stale-held, so `rate()` keeps returning a "
                        "decaying value until fewer than two samples remain in the rate "
                        "window -- and `$__rate_interval` grows with the range. Measured "
                        "on the partial-replica-loss run, one replica scaled away at "
                        "+185s: ungated, its line ran to +210s at a 1m rate interval, "
                        "+270s at 2m, +450s at 5m and past the end of the run at 10m, "
                        "fading toward zero the whole way. Gated, it ends at +210s in "
                        "every one of those, at its true last rate rather than a "
                        "decayed one." + PARA +
                        "So at this board's usual range the gate changes nothing -- a 1m "
                        "rate window expires before the 40s liveness window does. It is "
                        "load-bearing when you widen the range to look at a past "
                        "incident, which is exactly when a six-minute fade would mislead "
                        "you." + PARA +
                        "Note the legend is not evidence here: Grafana lists every series "
                        "that has data anywhere in the range, so a departed replica keeps "
                        "its legend entry after its line has stopped. Read the line.",
                   unit="reqps"),
    ]

    panels += [
        timeseries(lay, "Loop rate by loop",
                   [(f'rate(pipeline_loop_iterations_total{{{f}}}[$__rate_interval])',
                     "{{loop}} {{service_instance_id}}")],
                   desc="Every watched loop's actual cadence. l2-gate should sit at "
                        "0.2/s, processor-liveness and queue-depth at 0.1/s." + PARA +
                        "**This is what the liveness health checks cannot say.** A stale "
                        "window is binary -- it fires at 15s or 30s and says nothing "
                        "before that -- while a loop running at 0.12/s instead of 0.2/s "
                        "is degrading and still green on every probe." + PARA +
                        "Zero means the loop is gone, and it is a READING rather than an "
                        "absence: the counter is seeded with Add(0) per loop at startup, "
                        "so the series exists from the first export whether or not the "
                        "loop has ever run. An empty panel here is a process that is not "
                        "reporting at all.",
                   unit="reqps", decimals=2),

        timeseries(lay, "Consumer duration by disposition",
                   [(seeded(f'sum by (queue,disposition) '
                            f'(rate(pipeline_consumer_duration_seconds_sum{{{f}}}'
                            f'[$__rate_interval])) '
                            f'/ sum by (queue,disposition) '
                            f'(rate(pipeline_consumer_duration_seconds_count{{{f}}}'
                            f'[$__rate_interval]))',
                            f'group by (queue,service_instance_id) (last_over_time('
                            f'pipeline_consumer_duration_seconds_count{{{f}}}[$__range]))',
                            DISPOSITIONS),
                     "mean {{queue}} {{disposition}} {{service_instance_id}}")],
                   desc="How long a delivery was held, on every path including the ones "
                        "that never reached a handler. Split by disposition so a slow "
                        "success and a slow refusal cannot average into a number "
                        "describing neither." + PARA +
                        "**All three dispositions are seeded, so `requeued` and `parked` "
                        "hold the legend at zero when no delivery took those paths.** A "
                        "zero here is NOT a fast refusal -- it is the absence of one, and "
                        "the way to tell them apart is `Consumer paths` above: a real "
                        "fast path has a non-zero rate there, a seeded one does not. The "
                        "seed exists because a legend listing `acked` alone cannot be "
                        "told from a board where the two failure paths were never "
                        "instrumented." + PARA +
                        "**Wider than the pipeline.process.duration it replaces**, which "
                        "measured the author's transform alone and so was blank for every "
                        "delivery that bounced off a shut gate -- exactly the deliveries "
                        "worth timing during a store outage." + PARA +
                        "A mean rather than a quantile, deliberately: quantiles off this "
                        "ladder are interpolation between rung edges, and at the sample "
                        "counts this board sees they flip between levels rather than "
                        "moving.",
                   unit="s"),

        # The produce side is filtered by DESTINATION, not by this board's service filter:
        # the processor's work queue is published to by the ORCHESTRATOR, so filtering the
        # correction term by processor service_name selects the processor's own sends --
        # destination orchestrator-result -- and the join then matches nothing at all.
        queue_wait_panel(lay, f, 'destination=~"processor-$processorId"'),
    ]

    # The pipeline tier is 13 panels against a 3-across grid, so the last one sits
    # alone. Break the line here rather than letting the causes pair wrap around it:
    # exception rate and process restarts are read together, and the grid would
    # otherwise put one beside a pipeline panel and the other a row below.

    # full=True: this board absorbs the runtime panels an operator would otherwise
    # leave the board to find. SKP Runtime, which used to hold them, has been deleted.
    # The baseapi board still carries only the original pair.
    rt = row(lay, "Runtime", collapsed=True)
    # Exception rate leads the runtime panels rather than sitting on a visible row. It was
    # on the visible tier because a rising exception rate is a cause an operator should not
    # have to expand a row to find -- that argument is overridden here deliberately.
    rt["panels"] = causes_row(lay, f, w=8, restarts=False) + runtime_row(lay, f, full=True)
    panels.append(rt)

    # Titles aligned to the instruments. See PIPELINE_PANELS.
    relabel(panels, PROCESSOR_PANELS)

    # Subject rows, then positions from the final order. Both are post-passes:
    # see regroup() and relayout().
    panels = relayout(regroup(panels, worker_plan(["Identity ready"], ["Identity ready by replica"])))

    # Grafana 11.1 axis compatibility. Applied to THIS board only, matching the standing
    # scope; the orchestrator and flow boards carry the same latent defect through
    # depth_panels() and pipeline_shared() and are deliberately left for a separate call.
    for title in grafana11_axis_fix(panels):
        print(f"  grafana11 axis fix: dropped decimals on {title}")

    return dashboard(
        uid="skp-processor",
        title="SKP Processor",
        description=("Processor replicas, selected by processor id and replica. Name and "
                     "version come from the database row via the two-stage boot, so they "
                     "are properties of the processor id rather than axes of their own."),
        variables=[
            var_datasource(),
            # all_value=None is load-bearing here. This is the only board whose
            # service_name is a real selector rather than a constant, and with ".*" the
            # All option matched the orchestrator too -- the board rendered
            # next-step-handoff and process-dispatch, which no processor ever produces.
            # Two selectors, not four. `Processor image` and `Version` are gone: a
            # processor takes both from its database row, so they are properties of the
            # processor id rather than independent axes, and selecting one combination
            # that never existed produced an empty board.
            var_query("processorId", "Processor id",
                      'label_values(pipeline_identity_ready_ratio, processorId)'),
            var_query("service_instance_id", "Replica",
                      'label_values(pipeline_identity_ready_ratio{processorId=~"$processorId"}, service_instance_id)'),
            # The verdict tier's lookback, chosen by the reader instead of compiled in.
            # It feeds both the query and the panel title, so the two cannot disagree.
            # Single-select: a multi-select All would interpolate to `.*`, which is not
            # a duration and would not parse.
        ],
        panels=panels,
        links=NAV,
        tags=["skp", "skp-processor", "pipeline"],
    )


