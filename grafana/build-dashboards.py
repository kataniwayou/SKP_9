def since_shared(layout, f, restarts=True, by_=""):
    """The same fault counters over the visible range, for the Since tier.

    `restarts` drops the JIT-reset restart stat for a caller that measures restarts
    properly. It defaults to True so every other board is unchanged; the processor board
    passes False, because `resets()` on the JIT counter CANNOT SEE a restart on this
    deployment -- see RESTARTS below for the measurement -- and it carries
    `pipeline.process.start.timestamp` instead, which moves exactly once per process.

    The verdict tier above answers "is it broken right now" and goes green again when a
    fault stops. That is what makes its colour worth reading -- and it is also how an
    operator arriving five minutes late misses the event entirely. So the totals are not
    dropped, they are moved: same instruments, same helper, `$__range` instead of a fixed
    five minutes, under a row header that says which tense it is in.

    This mirrors the split the Flow board has had from the start (row 1 "is it broken
    right now?", row 2 "what has already happened?"). The worker boards had one row doing
    both jobs, and the sticky half won: every one of these read non-zero on a healthy
    stack.
    """
    seed = (f'group by ({by_}) (last_over_time(pipeline_gate_open_ratio{{{f}}}[$__range]))'
            if by_ else "")

    panels = [
        stat(layout, "Not acked",
             [recent(f'pipeline_messages_consumed_total{{{f},'
                     f'disposition=~"requeued|parked"}}', by_=by_, carrier=seed)],
             desc="Deliveries refused or sent back over the visible range.",
             thresholds=T_WARN, decimals=0),
        stat(layout, "Egress faults",
             [recent(f'pipeline_messages_produced_total{{{f},'
                     f'outcome=~"transient|unroutable|refused"}}', by_=by_, carrier=seed)],
             desc="Any send that did not reach the broker, over the visible range.",
             thresholds=T_WARN, decimals=0),
        stat(layout, "Dead-lettered",
             [f'sum(max by (queue) '
              f'(last_over_time(pipeline_deadletter_depth{{{f}}}[2m])))'],
             desc="Work this service refused that **nobody has dealt with**. Should be "
                  "0. Anything else is a run that lost progress permanently and is still "
                  "sitting in a queue with no consumer." + PARA +
                  "**The queue-by-queue breakdown is on the pipeline tier below.**" + PARA +
                  "`max by (queue)` before the sum is load-bearing: every replica probes "
                  "the same queues and reports the same depth, because a queue depth is "
                  "a property of the broker rather than of the replica asking." + PARA +
                  "**No `or vector(0)` here, deliberately.** Nothing reporting is not the "
                  "same fact as nothing dead-lettered, and a fallback to 0 would render "
                  "the two identically in green -- which is exactly the defect the hop-gap "
                  "stats were carrying. On the processor board this reads as text rather "
                  "than as a reassuring zero, because that deployment has a dead-letter "
                  "queue and no probe measuring it.",
             thresholds=T_WARN, decimals=0,
             no_value="not probed"),
    ]

    if not restarts:
        return panels

    panels.append(
        stat(layout, "Process restarts",
             [f'sum({RESTARTS % f}) or vector(0)'],
             desc="Process starts across every replica of this service in the visible "
                  "range. **Read this before believing any other number on the Since "
                  "tier.**" + PARA +
                  "A restart renumbers channels, ends and restarts every series under a "
                  "new identity, and puts tens of messages on the hop gaps that are not "
                  "lost. Measured here: 18 over a three-hour range -- six for each of "
                  "the three orchestrator replicas -- while `Workers reporting` sat "
                  "green at 5 and `Workers missing (5m)` at 0, because every restart had "
                  "completed and been replaced before either could see it." + PARA +
                  "Until now this number appeared nowhere except the bottom of SKP "
                  "Runtime, below fifteen GC panels, and behind a collapsed row on the "
                  "boards an operator opens first.",
             thresholds=T_WARN, decimals=0))
    return panels


