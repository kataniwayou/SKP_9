# Threshold sets. Grafana reads steps in ascending order; the first has value null.
T_FAULT = [{"color": "green", "value": None}, {"color": "red", "value": 0.0001}]
T_POSTURE = [{"color": "red", "value": None}, {"color": "green", "value": 1}]
T_EXACTLY_ONE = [{"color": "red", "value": None},
                 {"color": "green", "value": 1},
                 {"color": "red", "value": 2}]
# No colour at all. Correct ONLY for a number with no failure value -- `In-flight` is
# healthy at 0 and healthy at 40, and inventing a step would be inventing a fact.
#
# It is NOT correct for a presence count, and it was being used as one. On a row titled
# "is it broken?" the colour IS the signal: it is what a reader scans before reading any
# digits. `Workers reporting` and `Pods reporting` both carried this, which meant the two
# panels that answer "do the processes still exist" could not go red when they did not.
T_NEUTRAL = [{"color": "text", "value": None}]


# Queue depth in messages. DEPLOYMENT-SPECIFIC, like the flow band, and measured rather than
# chosen: over a clean four-minute window every orchestrator queue held a flat 0, while the
# processor work queue ran mean 0.65 with a max of 3. That burst is structural rather than noise --
# a cron fire dispatches a batch, PrefetchCount is 1, and two replicas drain it one message at a
# time -- so the green band has to clear it.
#
# Green below 5, which is above the measured healthy max with headroom. Orange to 20. Red beyond,
# which at this workload's ~0.4 dispatches/s is roughly a minute of nothing being consumed.
#
# NOTE WHAT THIS IS AND IS NOT FOR. Depth is the DEGRADATION signal -- a consumer slower than its
# producer, which nothing else here can see. It is a poor outage signal, and deliberately not tuned
# to be one: with the processor deployment scaled to zero the queue reached only 4 in ninety
# seconds, because a stalled pipeline stops feeding itself. `Queues unconsumed` beside it is the
# sharp signal for a total stop, and it moves within one liveness window.
DEPTH_ORANGE = 5

# THE DOOR-TO-DOOR STEP THRESHOLDS ARE GONE, WITH THE INSTRUMENT THEY COLOURED.
#
# `Step p95` and `Step duration p95 / p99` read `pipeline.step.elapsed`, retired by the
# metrics rewrite (section 6 of the 2026-08-26 spec). They were the only two panels on any
# board that measured what a WORKFLOW experiences rather than what a component does --
# healthy p95 0.050-0.060s, and 0.973s under the S10 fault that no other panel could see.
#
# Nothing here replaces that. `Queue wait by queue` plus `Consumer duration by
# disposition` decompose the same interval per hop, but no panel now sums them end to end.
# Recorded rather than quietly dropped, because the gap is real.


def normal_upto(ceiling):
    """A reference line at the top of measured-normal: green below it, orange above.

    Not an alarm threshold -- these panels have no failure mode that a single number
    separates. It answers the question a stat row cannot: *is what I am looking at the
    normal value?* Without it an operator has to already know that 24ms is right, and
    "know the number" is not something a dashboard should require.
    """
    return [{"color": "green", "value": None}, {"color": "orange", "value": ceiling}]
