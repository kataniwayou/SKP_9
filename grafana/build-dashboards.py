# ---------------------------------------------------------------------------
# reading a stale-held gauge, and counting a fault that is rare
# ---------------------------------------------------------------------------

# The collector's prometheus exporter keeps publishing a series after the process that
# fed it is gone, and Prometheus's own 5-minute lookback holds it after that. So a plain
# gauge selector reports replicas that no longer exist, at whatever value they held when
# they died.
#
# Measured, not theorised. During the chaos suite's orchestrator scenario all three
# orchestrator replicas were deleted for 58 seconds; throughout that window
# `min(pipeline_consumer_consuming_ratio)` stayed 1, `min(pipeline_gate_open_ratio)`
# stayed 1, and `count(count by (service_instance_id) (pipeline_gate_open_ratio))` stayed
# 5. In the processor scenario the same count went 5 -> 7 while two of five workers were
# being deleted, because the dead replicas were held alongside the new ones.
#
# `last_over_time(x[LIVENESS])` yields only series with a real sample inside the window,
# which is what "this replica is still reporting" means here.
#
# 40s, and the number is measured rather than chosen. The export cadence is 10s against a
# 15s scrape, so the effective sample spacing is 15s and the window has to survive one late
# sample without declaring a healthy replica dead -- and it has to be tight enough that a
# replica which vanishes for a minute falls out of it before its replacement starts
# reporting. At the old 60s cadence the equivalent number was 100s; 2m failed outright,
# never dipping on three recorded ~58s disappearances.
LIVENESS = "40s"


def live(series):
    """A gauge restricted to replicas that have actually reported recently."""
    return f"last_over_time({series}[{LIVENESS}])"


# The verdict tier answers "is it broken RIGHT NOW". This is the window it asks over.
# Five minutes rather than the range, for the reason `Workers missing (5m)` uses a fixed
# window: a verdict stat whose meaning changes when the reader zooms is not a verdict.
VERDICT_WINDOW = "5m"


def recent(series, window="$__range"):
    """A fault counter read as growth over a window -- correct at series birth AND
    correct across a process restart, and NOT sticky for the life of the process.

    Supersedes `counted()`, which is kept below only because the alert rules in
    k8s/02-configmaps.yaml still carry that shape and this file is the place the
    difference is written down.

    Two things break a naive count of a rare fault, and this form is the smallest one
    that survives both:

    - **Series birth.** These counters have no series at all in health -- the .NET
      counter is created on first increment -- so the first ever fault arrives as a
      series whose very first exported sample is already non-zero. `increase()` measures
      growth WITHIN the window and reports 0 for exactly that case, which is the case a
      verdict tier exists to catch. The `born` term covers it: nothing at the offset is
      `vector(0)`, so the whole of the current value is counted as growth.

    - **Counter reset.** A replica restarts, the counter returns to zero, and a plain
      now-minus-then subtraction goes negative. The `grew` term covers it, because
      `increase()` is reset-aware. Taking the larger of the two keeps whichever term is
      the one telling the truth.

    WHY THIS REPLACES `counted()`. That helper took the larger of in-window growth and
    `max_over_time`, and `max_over_time` of a monotonic counter IS its current value --
    the total since the process started, not since the window began. So it did not
    report a count over the range at all; it reported a lifetime total that happened to
    equal the range count only when the process was younger than the range. Every
    description saying "counted over the visible range" was therefore describing
    something the expression did not compute.

    Measured on this stack, orchestrator channel resets over a 3h range:

        counted()          63     <- the process lifetime total
        recent("3h")       54.2   <- what actually happened in the visible 3 hours
        recent("5m")        0     <- what is happening now

    And it made the verdict tier permanently non-green. `Not acked` read 1 on both
    worker boards against a single requeue that happened MORE than three hours earlier:
    `counted()` 1, `recent("3h")` 0. A verdict row that warns at rest trains an operator
    to ignore the colour, which costs more than the stale fact was worth.
    """
    grew = f"sum(increase({series}[{window}])) or vector(0)"
    born = (f"clamp_min((sum({series}) or vector(0)) "
            f"- (sum({series} offset {window}) or vector(0)), 0)")
    return f"(({grew}) > ({born})) or ({born})"


def counted(series, window="$__range"):
    """SUPERSEDED by recent(). Retained as documentation of the alert rules' shape.

    Nothing in this file calls it. The five rules in k8s/02-configmaps.yaml still carry
    this form, and changing them is a Prometheus config edit -- which discards the whole
    TSDB on restart -- so the divergence is recorded here rather than papered over. Both
    forms catch a first-ever fault; only `recent()` stops reporting one that is over.

    Original note follows.

    A fault counter read as a count over the range, correct at series birth.

    Fault counters here have no series at all in health -- the .NET counter is created on
    first increment -- so the first burst of a given fault type appears as a series whose
    very first exported sample is already non-zero. `increase()` measures growth WITHIN
    the window and therefore reports 0 for exactly that case: the first time a fault ever
    happens, which is the case the verdict tier exists to catch.

    Measured at the OLD 60s export cadence, which is when this shape was chosen: the
    broker scenario produced two transient publishes and one parked delivery.
    `sum(increase(...))` read 0 for all three for the rest of the run, while the
    rate-based stats these replace read 0.00 for the same reason plus the 240s rate
    window that cadence forced. This form -- the larger of the in-window growth and the
    absolute total -- read 2 and 1. The cadence is 10s now and the rate window 60s, which
    narrows the second half of that argument but not the first: the series-birth problem
    is a property of the .NET counter, not of the window, so this form is still required.

    The alert rules in k8s/02-configmaps.yaml carry the same shape for the same reason --
    see EgressFaults there, which shipped as bare `increase()` and could not have caught
    a first-ever fault.

    Consequence worth knowing: once a fault series exists it is exported for the life of
    the process, so this stat stays non-zero until the replica restarts. That is why the
    stats using it are thresholded warn-at-one rather than red: a fault that happened
    twenty minutes ago should not vanish from the verdict tier, but it should not read as
    an outage in progress either.
    """
    grew = f"sum(increase({series}[{window}])) or vector(0)"
    total = f"sum(max_over_time({series}[{window}])) or vector(0)"
    return f"(({grew}) > ({total})) or ({total})"


class Layout:
    """Assigns gridPos left-to-right, wrapping at the 24-column grid."""

    def __init__(self):
        self.x = 0
        self.y = 0
        self.row_h = 0

    def place(self, w, h):
        if self.x + w > 24:
            self.x = 0
            self.y += self.row_h
            self.row_h = 0
        pos = {"h": h, "w": w, "x": self.x, "y": self.y}
        self.x += w
        self.row_h = max(self.row_h, h)
        return pos

    def newline(self):
        if self.x:
            self.x = 0
            self.y += self.row_h
            self.row_h = 0


_uid_counter = [0]


def _next_id():
    _uid_counter[0] += 1
    return _uid_counter[0]


def targets(exprs):
    out = []
    for i, e in enumerate(exprs):
        expr, legend = e if isinstance(e, tuple) else (e, "")
        out.append({
            "refId": chr(ord("A") + i),
            "datasource": DS,
            "expr": expr,
            "legendFormat": legend,
            "range": True,
            "editorMode": "code",
        })
    return out


def stat(layout, title, exprs, desc="", thresholds=T_FAULT, unit="short",
         decimals=None, w=3, h=4, text_mode="auto", no_value=None):
    return {
        "id": _next_id(),
        "type": "stat",
        "title": title,
        "description": desc,
        "datasource": DS,
        "gridPos": layout.place(w, h),
        "targets": targets(exprs),
        "options": {
            "reduceOptions": {"calcs": ["lastNotNull"], "fields": "", "values": False},
            "orientation": "auto",
            "textMode": text_mode,
            "colorMode": "value",
            "graphMode": "area",
            "justifyMode": "auto",
        },
        "fieldConfig": {
            "defaults": {
                "unit": unit,
                "decimals": decimals,
                "mappings": [],
                "color": {"mode": "thresholds"},
                "thresholds": {"mode": "absolute", "steps": thresholds},
                # `or vector(0)` covers an empty result. It does NOT cover NaN, which is
                # what a quantile over zero traffic produces, so a stat that can go NaN
                # needs text as well or it renders indistinguishable from a broken query.
                **({"noValue": no_value} if no_value is not None else {}),
            },
            "overrides": [],
        },
    }


def timeseries(layout, title, exprs, desc="", unit="short", w=8, h=8,
               stack=False, fill=8, legend_mode="list", legend_pos="bottom",
               minv=None, maxv=None, thresholds=None, draw_style="line",
               decimals=None, no_value=None, soft_max=None):
    custom = {
        "drawStyle": draw_style,
        "lineWidth": 1,
        "fillOpacity": fill,
        "gradientMode": "opacity",
        "spanNulls": False,
        "showPoints": "never",
        "pointSize": 4,
        "axisPlacement": "auto",
        "axisLabel": "",
        "scaleDistribution": {"type": "linear"},
        "stacking": {"mode": "normal" if stack else "none", "group": "A"},
        "hideFrom": {"legend": False, "tooltip": False, "viz": False},
        "thresholdsStyle": {"mode": "line" if thresholds else "off"},
    }
    # A ratio that sits flat at zero in health gets an axis scaled to whatever transient
    # once spiked -- after a rollout, 10000%. A soft max floors the axis so the healthy
    # line is readable, while still expanding if the data genuinely exceeds it.
    if soft_max is not None:
        custom["axisSoftMax"] = soft_max
    defaults = {
        "unit": unit,
        "decimals": decimals,
        "custom": custom,
        "mappings": [],
        "color": {"mode": "palette-classic"},
        "thresholds": {"mode": "absolute",
                       "steps": thresholds or [{"color": "green", "value": None}]},
    }
    if minv is not None:
        defaults["min"] = minv
    if maxv is not None:
        defaults["max"] = maxv
    # A breakdown-by-label panel cannot use `or vector(0)` -- the fallback would draw an
    # unlabelled series that means nothing. noValue is the equivalent for those: the
    # panel states that nothing matched because nothing is wrong, instead of rendering
    # the same blank a broken query renders.
    if no_value is not None:
        defaults["noValue"] = no_value
    return {
        "id": _next_id(),
        "type": "timeseries",
        "title": title,
        "description": desc,
        "datasource": DS,
        "gridPos": layout.place(w, h),
        "targets": targets(exprs),
        "options": {
            "legend": {"displayMode": legend_mode, "placement": legend_pos,
                       "showLegend": True, "calcs": []},
            "tooltip": {"mode": "multi", "sort": "desc"},
        },
        "fieldConfig": {"defaults": defaults, "overrides": []},
    }


# Value -> (label, colour) for the posture strips.
#
# The label is not decoration: a state timeline legends itself by DISTINCT VALUE, and
# with colour driven off thresholds alone that legend reads "< 1" and "1+" -- which tells
# a reader nothing about which end is the healthy one. Naming the states puts the answer
# on the panel.
#
# The colour is carried here rather than by a threshold step because these gauges do not
# all mean the same thing at 0. A follower replica is 0 on pipeline.leader and is working
# exactly as designed; rendering it red -- which a red-below-1 threshold does, and did --
# says the opposite of what the panel's own description says. Only the states that are
# genuinely wrong are red.
M_CONSUMING = {"0": ("stopped", "red"), "1": ("consuming", "green")}
M_GATE = {"0": ("shut", "red"), "1": ("open", "green")}
M_LEADER = {"0": ("follower", "semi-dark-blue"), "1": ("leader", "green")}
M_ADMITTED = {"0": ("not admitted", "red"), "1": ("admitted", "green")}
# Orange rather than red: a processor waiting for a matching processor row is the
# designed two-stage boot, not a crash. It still is not doing work.
M_READY = {"0": ("not ready", "orange"), "1": ("ready", "green")}
M_POSTURE = {"0": ("down", "red"), "1": ("ok", "green")}


def mapping(pairs):
    return [{"type": "value",
             "options": {k: {"text": t, "color": c, "index": i}
                         for i, (k, (t, c)) in enumerate(sorted(pairs.items()))}}]


def statetimeline(layout, title, exprs, desc="", w=8, h=8, thresholds=None,
                  mappings=None, no_value=None):
    """A 0/1 posture drawn as bands per series rather than as overlaid lines.

    WHY THIS PANEL TYPE EXISTS HERE. Six panels drew booleans on a shared numeric axis,
    and a shared axis is the wrong instrument for them: every series sits at exactly 1 in
    health, so they render as one line and only the last one drawn is visible. Observed
    on the live boards -- `Leader by replica` drew three replicas as a single filled band
    with white slivers in it, and could not answer the question in its own title; five
    queues on `Consuming by queue` were one flat line at 1 for three hours.

    A state timeline gives each series its own row, so N series are N answers rather than
    one. It also renders the case those panels were written to show and could not: a
    series that ENDS leaves an empty row from that point (spanNulls and insertNulls both
    false), which is a replica that left, and is visually distinct from a row that drops
    to the failed colour, which is a replica that is present and not working.
    """
    return {
        "id": _next_id(),
        "type": "state-timeline",
        "title": title,
        "description": desc,
        "datasource": DS,
        "gridPos": layout.place(w, h),
        "targets": targets(exprs),
        "options": {
            # Collapse consecutive identical samples, or a 15s-resolution boolean draws
            # ~700 separate bands across a three-hour range.
            "mergeValues": True,
            "showValue": "never",
            "alignValue": "left",
            "rowHeight": 0.9,
            # No perPage. Setting it turns on Grafana's pager, which drew a "< 1 >"
            # control under every one of these for a single page of five rows.
            "legend": {"displayMode": "list", "placement": "bottom",
                       "showLegend": True, "calcs": []},
            "tooltip": {"mode": "single", "sort": "none"},
        },
        "fieldConfig": {
            "defaults": {
                "custom": {
                    "lineWidth": 0,
                    "fillOpacity": 70,
                    "spanNulls": False,
                    "insertNulls": False,
                    "hideFrom": {"legend": False, "tooltip": False, "viz": False},
                },
                # NOT thresholds, and the reason is the legend rather than the colour.
                # Grafana builds a state timeline's legend from the threshold STEPS
                # whenever the colour mode is `thresholds` and there is more than one
                # step -- which rendered as "< 1  1+" under every one of these panels,
                # naming neither state and telling a reader nothing about which end is
                # healthy. With a fixed mode it builds the legend from the distinct
                # values instead, so the value mappings' own labels appear: "consuming"
                # and "stopped", "leader" and "follower".
                #
                # Every colour therefore comes from the mappings. fixedColor is what a
                # value NONE of them names falls back to -- purple, deliberately unlike
                # any mapped state, so `leaders elected 2` on the Posture panel reads as
                # "this is not one of the states we know" rather than blending into ok.
                "color": {"mode": "fixed", "fixedColor": "purple"},
                "thresholds": {"mode": "absolute", "steps": thresholds or T_NEUTRAL},
                "mappings": mapping(mappings) if mappings else [],
                **({"noValue": no_value} if no_value is not None else {}),
            },
            "overrides": [],
        },
    }


def table(layout, title, exprs, desc="", w=8, h=8, exclude=(), rename=None,
          extra_transforms=(), overrides=()):
    return {
        "id": _next_id(),
        "type": "table",
        "title": title,
        "description": desc,
        "datasource": DS,
        "gridPos": layout.place(w, h),
        "targets": [dict(t, format="table", instant=True, range=False)
                    for t in targets(exprs)],
        "transformations": [
            {"id": "merge", "options": {}},
            # Instant queries still carry a Time column, identical on every row, which here
            # only steals width from the value.
            # Table format discards legendFormat, so a two-query table arrives with columns
            # called "Value #A" and "Value #B" and the reader has to guess which is which.
            {"id": "organize", "options": {
                "excludeByName": {k: True for k in exclude},
                "renameByName": rename or {},
            }},
            *extra_transforms,
        ],
        "options": {"showHeader": True, "footer": {"show": False, "reducer": ["sum"]}},
        "fieldConfig": {
            "defaults": {
                "custom": {"align": "auto", "cellOptions": {"type": "auto"},
                           "inspect": False},
                "mappings": [],
                "thresholds": {"mode": "absolute", "steps": T_NEUTRAL},
            },
            "overrides": list(overrides),
        },
    }


